export const LANGS: Record<string, Dict> = { en, pt, es };
export const LANG_NAMES: Record<string, string> = { en: 'English', pt: 'Português', es: 'Español' };

let current: Dict = en;
export let lang = 'en';

export function setLang(code: string): void {
  const c = (code || 'en').slice(0, 2).toLowerCase();
  lang = LANGS[c] ? c : 'en';
  current = LANGS[lang];
}

export function t(key: StrKey, vars?: Record<string, string | number>): string {
  let s = current[key] ?? en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}
